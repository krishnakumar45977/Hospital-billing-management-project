CREATE TABLE DEPARTMENT (
    DEPT_ID NUMBER(5) PRIMARY KEY,
    DEPT_NAME VARCHAR2(50) NOT NULL,
    LOCATION VARCHAR2(30)
);

CREATE TABLE DOCTOR (
    DOCTOR_ID NUMBER(5) PRIMARY KEY,
    DOCTOR_NAME VARCHAR2(50) NOT NULL,
    DEPT_ID NUMBER(5) NOT NULL,
    SPECIALIZATION VARCHAR2(50),
    FEES NUMBER(8,2) CHECK (FEES > 0),

    CONSTRAINT FK_DOCTOR_DEPT
        FOREIGN KEY (DEPT_ID)
        REFERENCES DEPARTMENT(DEPT_ID)
);

CREATE TABLE PATIENT (
    PATIENT_ID NUMBER(5) PRIMARY KEY,
    PATIENT_NAME VARCHAR2(50) NOT NULL,
    GENDER CHAR(1),
    CITY VARCHAR2(30) NOT NULL,
    PHONE VARCHAR2(15) UNIQUE,
    EMAIL VARCHAR2(50) UNIQUE
);

CREATE TABLE APPOINTMENT (
    APPOINTMENT_ID NUMBER(6) PRIMARY KEY,
    PATIENT_ID NUMBER(5) NOT NULL,
    DOCTOR_ID NUMBER(5) NOT NULL,
    APPOINTMENT_DATE DATE DEFAULT SYSDATE,
    STATUS VARCHAR2(20) DEFAULT 'SCHEDULED',

    CONSTRAINT FK_APPT_PATIENT
        FOREIGN KEY (PATIENT_ID)
        REFERENCES PATIENT(PATIENT_ID),

    CONSTRAINT FK_APPT_DOCTOR
        FOREIGN KEY (DOCTOR_ID)
        REFERENCES DOCTOR(DOCTOR_ID),

    CONSTRAINT CHK_APPT_STATUS
        CHECK (STATUS IN ('SCHEDULED', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE BILLING (
    BILL_ID NUMBER(6) PRIMARY KEY,
    APPOINTMENT_ID NUMBER(6) NOT NULL,
    AMOUNT NUMBER(10,2) CHECK (AMOUNT > 0),
    PAYMENT_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    BILL_DATE DATE DEFAULT SYSDATE,

    CONSTRAINT FK_BILL_APPT
        FOREIGN KEY (APPOINTMENT_ID)
        REFERENCES APPOINTMENT(APPOINTMENT_ID),

    CONSTRAINT CHK_PAYMENT_STATUS
        CHECK (PAYMENT_STATUS IN ('PAID', 'PENDING'))
);

