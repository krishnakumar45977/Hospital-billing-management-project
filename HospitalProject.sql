WITH DEPT_REVENUE AS (
    SELECT D.DEPT_ID, SUM(B.AMOUNT) AS TOTAL_REVENUE
    FROM DOCTOR D
    JOIN APPOINTMENT A ON D.DOCTOR_ID = A.DOCTOR_ID
    JOIN BILLING B ON A.APPOINTMENT_ID = B.APPOINTMENT_ID
    GROUP BY D.DEPT_ID
)
SELECT DE.DEPT_NAME, DR.TOTAL_REVENUE
FROM DEPARTMENT DE
JOIN DEPT_REVENUE DR ON DE.DEPT_ID = DR.DEPT_ID;

WITH PATIENT_SPEND AS (
    SELECT A.PATIENT_ID, SUM(B.AMOUNT) AS TOTAL_SPEND
    FROM APPOINTMENT A
    JOIN BILLING B ON A.APPOINTMENT_ID = B.APPOINTMENT_ID
    GROUP BY A.PATIENT_ID
)
SELECT P.PATIENT_NAME, NVL(PS.TOTAL_SPEND, 0) AS TOTAL_SPEND
FROM PATIENT P
LEFT JOIN PATIENT_SPEND PS ON P.PATIENT_ID = PS.PATIENT_ID;

WITH DOCTOR_APPOINTMENTS AS (
    SELECT DOCTOR_ID, COUNT(*) AS APPOINTMENT_COUNT
    FROM APPOINTMENT
    GROUP BY DOCTOR_ID
)
SELECT D.DOCTOR_NAME, DA.APPOINTMENT_COUNT
FROM DOCTOR D
JOIN DOCTOR_APPOINTMENTS DA ON D.DOCTOR_ID = DA.DOCTOR_ID
ORDER BY DA.APPOINTMENT_COUNT DESC;
